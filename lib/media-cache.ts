// Served sizes are a closed set: arbitrary widths would let clients fill the
// cache and the CPU with unique variants.
// Bump when variant encoding changes so browsers and the cache refresh.
const pipeline = "v1";

// null: original; number: allowed variant; undefined: invalid request.
export function mediaWidth(
  value: string | null | undefined,
  widths = mediaWidths,
) {
  if (value === null || value === undefined || value === "") return null;
  const width = Number(value);
  return widths.includes(width) && String(width) === value ? width : undefined;
}

// Media IDs are never reused for other bytes, so ID + size identify content.
export const mediaEtag = (id: string, width: number | null = null) =>
  `"${pipeline}-${id}-${width || "original"}"`;

export function notModified(req: Request, etag: string) {
  const header = req.headers.get("if-none-match");
  return (
    !!header &&
    header
      .split(",")
      .some((value: string) => value.trim().replace(/^W\//, "") === etag)
  );
}

// Private media: the browser keeps bytes but revalidates every use, so the
// server re-checks access each time and revocation applies immediately.
export const privateMediaCache = "private, no-cache";
// Site graphics are public and a new upload always gets a new ID.
export const immutableMediaCache = "public, max-age=31536000, immutable";

export function mediaResponse(
  bytes: BodyInit | Buffer | null | undefined,
  etag: string,
  { cache = privateMediaCache, contentType = "image/webp", headers = {} } = {},
) {
  return new Response(Buffer.isBuffer(bytes) ? new Uint8Array(bytes) : bytes, {
    headers: {
      "Content-Type": contentType,
      "Cache-Control": cache,
      ETag: etag,
      "X-Content-Type-Options": "nosniff",
      ...headers,
    },
  });
}

export function notModifiedResponse(
  etag: string,
  { cache = privateMediaCache, headers = {} } = {},
) {
  return new Response(null, {
    status: 304,
    headers: { "Cache-Control": cache, ETag: etag, ...headers },
  });
}

export const cacheDirectory = (env = process.env) =>
  path.resolve(
    /*turbopackIgnore: true*/
    env.MEDIA_CACHE_DIR || path.join(os.tmpdir(), "colabike-media-cache"),
  );
const variantPath = (
  id: string,
  width: number,
  env: NodeJS.ProcessEnv | undefined,
) => path.join(cacheDirectory(env), `${pipeline}-${id}-${width}.webp`);

// Variants are derived data: built once per (ID, width), stored outside the
// backed-up photos volume by default and rebuilt after a container restart.
// Callers must check access before asking for bytes.
export async function mediaVariant(
  id: string,
  width: number,
  readOriginal: () => Promise<Buffer>,
  env = process.env,
) {
  if (!siteGraphicWidths.includes(width))
    throw new Error("INVALID_MEDIA_WIDTH");
  return cachedFile(
    variantPath(id, width, env),
    async () => prepareThumbnail(await readOriginal(), width),
    env,
  );
}

// `name` must include every input/version and be server-built, never user input.
export async function cachedDerivative(
  name: string,
  build: () => Promise<Buffer>,
  env = process.env,
) {
  return cachedFile(path.join(cacheDirectory(env), name), build, env);
}
const builds = createMediaBuildQueue();
async function cachedFile(
  file: string,
  build: () => Promise<Buffer>,
  env: NodeJS.ProcessEnv,
) {
  try {
    return await readFile(file);
  } catch {
    /* Miss or unreadable cache. */
  }
  return builds.run(file, async (invalidated) => {
    // A reader may have missed just before the preceding build finished.
    try {
      return await readFile(file);
    } catch {
      /* Still cold. */
    }
    const bytes = await build();
    const temp = `${file}.${randomUUID()}.tmp`;
    try {
      if (!invalidated()) {
        await mkdir(path.dirname(file), { recursive: true, mode: 0o700 });
        await writeFile(temp, bytes, { mode: 0o600 });
        if (!invalidated()) {
          await rename(temp, file);
          // Purge can run while rename is pending. Never resurrect its entry.
          if (invalidated()) await rm(file, { force: true });
          else scheduleSweep(env);
        }
      }
    } catch {
      /* Full/read-only cache: deliver generated bytes. */
    } finally {
      await rm(temp, { force: true }).catch(() => {});
    }
    return bytes;
  });
}

// ACL checks belong to each request, outside the shared promise. Recheck after
// waiting/reading so revocation during a cold build does not deliver its bytes.
export async function revalidatedMedia(
  read: () => Promise<Buffer>,
  authorize: () => Promise<unknown>,
) {
  const bytes = await read();
  await authorize();
  return bytes;
}
export function mediaBusyResponse(error: unknown) {
  return error instanceof MediaCacheBusyError
    ? new Response(null, {
        status: 503,
        headers: { "Cache-Control": "no-store", "Retry-After": "1" },
      })
    : null;
}

// Working files that are not derived from a stored original (the previews of a
// backdrop removal, #370) live here too: the sweep and a restart clear them, and
// whoever asks must cope with a missing file. `name` is server-built.
export async function storeCacheFile(
  name: string,
  bytes: Buffer,
  env = process.env,
) {
  const file = path.join(cacheDirectory(env), name);
  await mkdir(path.dirname(file), { recursive: true, mode: 0o700 });
  const temp = `${file}.${randomUUID()}.tmp`;
  try {
    await writeFile(temp, bytes, { mode: 0o600 });
    await rename(temp, file);
  } catch (e) {
    await rm(temp, { force: true }).catch(() => {});
    throw e;
  }
  scheduleSweep(env);
}
export async function readCacheFile(name: string, env = process.env) {
  try {
    return await readFile(path.join(cacheDirectory(env), name));
  } catch {
    return null;
  }
}
export async function removeCacheFiles(names: string[], env = process.env) {
  await Promise.all(
    names.map((name) => {
      const file = path.join(cacheDirectory(env), name);
      builds.invalidate(file);
      return rm(file, { force: true }).catch(() => {});
    }),
  );
}

// Best-effort removal when a photo is deleted; a restart clears the rest.
export async function purgeMediaVariants(ids: string[], env = process.env) {
  await removeCacheFiles(
    ids.flatMap((id) =>
      siteGraphicWidths.map((width) =>
        path.basename(variantPath(id, width, env)),
      ),
    ),
    env,
  );
}

// Keep the cache under MEDIA_CACHE_MAX_MB (default 1024) by removing the
// oldest variants. Runs at most once per 200 new files.
let writes = 0;
function scheduleSweep(env: NodeJS.ProcessEnv | undefined) {
  if (++writes % 200) return;
  sweepMediaCache(env).catch(() => {});
}
const sweeps = new Map<string, Promise<number>>();
export function sweepMediaCache(env = process.env) {
  const directory = cacheDirectory(env);
  const existing = sweeps.get(directory);
  if (existing) return existing;
  const promise = sweep(env).finally(() => sweeps.delete(directory));
  sweeps.set(directory, promise);
  return promise;
}
async function sweep(env: NodeJS.ProcessEnv) {
  const limit = (Number(env.MEDIA_CACHE_MAX_MB) || 1024) * 1024 * 1024;
  const directory = cacheDirectory(env);
  const files = [];
  for (const name of await readdir(/*turbopackIgnore: true*/ directory)) {
    if (!name.endsWith(".webp") && !name.endsWith(".jpg")) continue;
    try {
      const info = await stat(path.join(directory, name));
      files.push({ name, size: info.size, mtime: info.mtimeMs });
    } catch {
      /* Files may disappear while the sweep is collecting them. */
    }
  }
  let total = files.reduce((sum, f) => sum + f.size, 0);
  if (total <= limit) return 0;
  let removed = 0;
  for (const f of files.sort((a, b) => a.mtime - b.mtime)) {
    if (total <= limit * 0.8) break;
    await rm(path.join(directory, f.name), { force: true });
    total -= f.size;
    removed++;
  }
  return removed;
}
